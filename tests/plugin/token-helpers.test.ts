import { equal, match, throws } from "node:assert/strict";
import { consumeOnce, expiresAt, isActiveToken } from "../../plugins/sdk-typescript/src/index.js";
import { consumeDigestToken, createDigestToken, numericOTP, randomToken, secretsEqual } from "../../plugins/sdk-typescript/src/tokens.js";

const token = { expiresAt: 100, used: false, projectId: "p" };
equal(consumeOnce(token, 0, (value) => value.projectId === "other"), undefined);
equal(token.used, false);
equal(consumeOnce(token, 99, (value) => value.projectId === "p"), token);
equal(consumeOnce(token, 99, () => true), undefined);
equal(isActiveToken({ expiresAt: 100 }, 100), false);
equal(isActiveToken({ expiresAt: NaN }, 0), false);
equal(isActiveToken({ expiresAt: 100 }, NaN), false);
throws(() => expiresAt(0, Infinity, "invalid expiry"), /invalid expiry/);
throws(() => expiresAt(0, 0, "invalid expiry"), /invalid expiry/);
const digest = createDigestToken("secret", "token", 0, 100, "invalid");
equal(consumeDigestToken(digest, "wrong", "token", 1), false);
equal(consumeDigestToken(digest, "secret", "wrong", 1), false);
equal(consumeDigestToken(digest, "secret", "token", 1), true);
equal(consumeDigestToken(digest, "secret", "token", 1), false);
equal(secretsEqual("a", "ab"), false);
match(numericOTP(), /^[1-9][0-9]{5}$/);
match(randomToken(32, "hex"), /^[a-f0-9]{64}$/);
