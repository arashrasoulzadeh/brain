package plugin

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// ManifestSDKTypes generates compile-time operation names from the same
// manifests used by the registry. Runtime authorization remains authoritative.
func ManifestSDKTypes(root string) (string, error) {
	locations, err := Discover(root)
	if err != nil {
		return "", err
	}
	manifests := make([]Manifest, 0, len(locations))
	for _, location := range locations {
		manifest, err := LoadManifest(location.ManifestPath)
		if err != nil {
			return "", err
		}
		manifests = append(manifests, manifest)
	}
	sort.Slice(manifests, func(i, j int) bool { return manifests[i].ID < manifests[j].ID })
	var out strings.Builder
	out.WriteString("// Generated by go run ./cmd/manifest-sdk; do not edit.\nexport interface ManifestOperations {\n")
	for _, manifest := range manifests {
		operations := make([]string, 0, len(manifest.Routes))
		for _, route := range manifest.Routes {
			operations = append(operations, strconv.Quote(route.Operation))
		}
		sort.Strings(operations)
		union := "never"
		if len(operations) > 0 {
			union = strings.Join(operations, " | ")
		}
		fmt.Fprintf(&out, "  %s: %s;\n", strconv.Quote(manifest.ID), union)
	}
	out.WriteString("}\n\nexport type ManifestOperation<Id extends keyof ManifestOperations> = ManifestOperations[Id];\n")
	return out.String(), nil
}
